export function translate(lang: Lang, key: TranslationKey): string {
  return dict[lang]?.[key] ?? dict[DEFAULT_LANG][key];
}

/** Picks the localized field from a record that has `x` / `xEn` variants. */
export function localized(
  value: string | null | undefined,
  valueEn: string | null | undefined,
  lang: Lang,
): string {
  if (lang === "en" && valueEn) return valueEn;
  return value ?? valueEn ?? "";
}
